/**
 * Merge the static seed posts with any AI-generated articles that were saved to the
 * database (via POST /api/admin/generate-articles). Generated posts win on duplicate slugs.
 */
export function getGeneratedBlogPosts(): BlogPost[] {
  try {
    const { getDatabase } = require('@/lib/db') as typeof import('@/lib/db');
    const db = getDatabase();
    if (!Array.isArray(db.blogPosts)) return [];
    return (db.blogPosts as BlogPost[]).filter(p => p && p.slug && p.title);
  } catch {
    return [];
  }
}

export function getAllBlogPosts(): BlogPost[] {
  const generated = getGeneratedBlogPosts();
  if (generated.length === 0) return BLOG_POSTS;
  const generatedSlugs = new Set(generated.map(p => p.slug));
  const seedOnly = BLOG_POSTS.filter(p => !generatedSlugs.has(p.slug));
  return [...seedOnly, ...generated];
}

export function getBlogPostBySlug(slug: string): BlogPost | undefined {
  return getAllBlogPosts().find(p => p.slug === slug);
}

export function getBlogCategories(): string[] {
  return Array.from(new Set(getAllBlogPosts().map(p => p.category)));
}

export function getBlogPostTitles(db?: any): string[] {
  const titles = BLOG_POSTS.map(p => p.title);
  try {
    if (db && Array.isArray(db.blogPosts)) {
      (db.blogPosts as BlogPost[]).forEach(p => p.title && titles.push(p.title));
    }
  } catch {}
  return titles;
}